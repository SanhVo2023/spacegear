// Writes src/lib/content-index.generated.ts: one static JSON import per entry file of the
// content/ and content/vi/ folder collections. The typed loader (src/lib/content.ts) also runs in the browser
// bundle and in the Worker, so it cannot list a folder at run time; this index lets it import
// every entry at build time. Entries are listed in file-name order; the loader sorts them by
// their `order` field. The build regenerates the index; `npm test` fails when it is stale.
// Paths resolve from this script's location, so the command works from any folder.
//   node scripts/build-content-index.mjs           write the index
//   node scripts/build-content-index.mjs --check   exit 1 if the index is out of date
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const COLLECTIONS = ["services", "engagements", "faqs", "team-roles", "testimonials", "articles"];
export const INDEX_FILE = "src/lib/content-index.generated.ts";
/** The project folder (the parent of scripts/), wherever the command runs from. */
export const ROOT = fileURLToPath(new URL("..", import.meta.url));
const ENTRY_NAME = /^[a-z0-9][a-z0-9_-]*\.json$/;

/** A file name to fix, not a bug: `issues` lists it the way ContentError does, so check-content prints it without a stack. */
export class EntryNameError extends Error {
  constructor(message) {
    super(message);
    this.name = "EntryNameError";
    this.issues = [message];
  }
}

/**
 * Entry files of one folder collection, sorted by name. Dotfiles (.gitkeep) are skipped. The
 * extension is matched in any case, so a name such as X.JSON is refused instead of skipped.
 */
export function listEntries(root, collection, dir = "content") {
  const folder = path.join(root, dir, collection);
  if (!fs.existsSync(folder)) return [];
  const names = fs.readdirSync(folder, { withFileTypes: true })
    .filter((entry) => entry.isFile() && !entry.name.startsWith(".") && entry.name.toLowerCase().endsWith(".json"))
    .map((entry) => entry.name);
  const bad = names.filter((name) => !ENTRY_NAME.test(name));
  if (bad.length) throw new EntryNameError(`Rename ${bad.map((name) => `${dir}/${collection}/${name}`).join(", ")}: entry file names use lowercase letters, digits, - and _ only.`);
  return names.sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
}

/** The two languages' collections in the index: English as COLLECTION_FILES (as before), Vietnamese as COLLECTION_FILES_VI. */
const INDEXED = [
  { dir: "content", prefix: "", name: "COLLECTION_FILES" },
  { dir: "content/vi", prefix: "vi_", name: "COLLECTION_FILES_VI" },
];

export function renderIndex(root = ROOT) {
  const imports = [];
  const exports = [];
  for (const { dir, prefix, name } of INDEXED) {
    const groups = [];
    for (const collection of COLLECTIONS) {
      const id = `${prefix}${collection.replaceAll("-", "_")}`;
      const rows = listEntries(root, collection, dir).map((file, index) => {
        imports.push(`import ${id}_${index} from "../../${dir}/${collection}/${file}" with { type: "json" };`);
        return `    { file: ${JSON.stringify(file)}, data: ${id}_${index} },`;
      });
      groups.push(rows.length ? `  ${JSON.stringify(collection)}: [\n${rows.join("\n")}\n  ],` : `  ${JSON.stringify(collection)}: [],`);
    }
    exports.push("", `export const ${name}: Record<CollectionName, CollectionFile[]> = {`, ...groups, "};");
  }
  return [
    "// Generated by scripts/build-content-index.mjs. Do not edit by hand.",
    "// Lists every entry of the content/ and content/vi/ folder collections so that src/lib/content.ts can",
    "// import them statically. Run `npm run content:index` after adding, renaming or removing an entry.",
    'import type { CollectionFile, CollectionName } from "./content-model.ts";',
    ...imports,
    ...exports,
    "",
  ].join("\n");
}

export function readIndex(root = ROOT) {
  const file = path.join(root, INDEX_FILE);
  return fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : "";
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  // A bad entry name (or an unreadable folder) is an editing problem: print it plainly, no stack trace.
  try {
    const next = renderIndex(ROOT);
    const fresh = readIndex(ROOT) === next;
    if (process.argv.includes("--check")) {
      if (!fresh) { console.error(`${INDEX_FILE} is out of date. Run: npm run content:index`); process.exitCode = 1; }
      else console.log("Content index is up to date.");
    } else if (!fresh) {
      fs.writeFileSync(path.join(ROOT, INDEX_FILE), next);
      console.log(`Wrote ${INDEX_FILE}.`);
    } else console.log("Content index is up to date.");
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
